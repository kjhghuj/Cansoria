import type { MedusaContainer } from "@medusajs/framework/types"
import { Modules } from "@medusajs/framework/utils"
import { orderAccessUrl } from "./access-tokens"

export type NotificationPayload = {
  to: string
  channel: string
  template: string
  idempotency_key?: string
  data: Record<string, unknown>
}

/**
 * A PENDING record older than this window was almost certainly abandoned by a
 * crashed or killed worker (the send path is bounded by the queue timeout);
 * the recovery job and this module both treat it as failed so the
 * idempotency key becomes reusable and the email can go out again.
 */
export const STALE_PENDING_MS = 10 * 60_000

/** Raised when sending must be retried later (worker requeue) rather than failed. */
export class NotificationRetryError extends Error {}

/**
 * The module's typed surface omits the generated record filters/updates its
 * own runtime (and this fix) rely on; model fields are filterable and
 * updateNotifications is generated by the MedusaService factory.
 */
type NotificationRecords = {
  createNotifications(payload: NotificationPayload): Promise<unknown>
  listNotifications(filters: Record<string, unknown>, config?: Record<string, unknown>): Promise<NotificationRecordShape[]>
  updateNotifications(entries: Array<Record<string, unknown>>): Promise<unknown[]>
  retrieveNotification(id: string): Promise<NotificationRecordShape>
}
type NotificationRecordShape = {
  id: string
  to: string
  channel: string
  template: string | null
  data: Record<string, unknown> | null
  idempotency_key: string | null
  status: string
  created_at: string | Date
}

type PriorNotification = Pick<NotificationRecordShape, "id" | "status" | "created_at">

function priorAgeMs(prior: PriorNotification): number {
  const created = new Date(prior.created_at).getTime()
  return Number.isFinite(created) ? Date.now() - created : Number.POSITIVE_INFINITY
}

function isPayloadData(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value)
}

/**
 * Only a record the framework itself marked "success" proves delivery. The
 * framework silently skips the send (and answers undefined) when a PENDING
 * record with the same key appears concurrently; callers must treat that as
 * retryable, never as delivered — business "email sent" flags depend on it.
 */
function verifiedDelivery(record: unknown): NotificationRecordShape {
  if (!record || typeof record !== "object" || (record as NotificationRecordShape).status !== "success") {
    throw new NotificationRetryError("Notification delivery was not confirmed as successful; retry later")
  }
  return record as NotificationRecordShape
}

/**
 * Send a notification with durable retry semantics around the framework's
 * idempotency handling:
 * - SUCCESS with the same key: already delivered, dedupe.
 * - FAILURE with the same key: the framework's retry path updates a freshly
 *   generated id that was never created, so its post-send update fails.
 *   Rename the failed record (kept for auditing) to free the unique key and
 *   create a clean record for the retry.
 * - Stale PENDING (> STALE_PENDING_MS): the sender died mid-flight; treat like
 *   FAILURE so the send is retried.
 * - Fresh PENDING: another attempt may be in flight right now; surface a
 *   retryable error instead of silently skipping the send.
 *
 * The pre-query and the framework's own create are serialized behind a
 * per-key lock: without it a second sender can insert a PENDING record
 * between the two, skipping the send while the caller records success.
 *
 * Retries reuse the first attempt's stored payload data — including across a
 * crash between the rename and the create, where the original key is already
 * free but the renamed attempt record still exists. The provider's
 * idempotency contract requires the same key AND the same content, and
 * regenerated data (e.g. a freshly signed link) would be rejected as a
 * conflicting reuse of the key.
 *
 * Any send failure propagates: callers must rethrow so the event worker
 * requeues the work instead of ack-ing a dropped email.
 */
export async function sendNotification(container: MedusaContainer, payload: NotificationPayload) {
  const notifications = container.resolve(Modules.NOTIFICATION) as unknown as NotificationRecords
  if (!payload.idempotency_key) {
    return verifiedDelivery(await notifications.createNotifications(payload))
  }
  const locking = container.resolve(Modules.LOCKING)
  const key = payload.idempotency_key
  return await locking.execute(`notification:${key}`, async () => {
    const existing = await notifications.listNotifications({ idempotency_key: key })
    const prior = existing?.[0]
    if (!prior) {
      // A previous retry may have died after freeing the key: the renamed
      // attempt record still holds the payload the provider may have seen.
      // Recover that content instead of sending fresh data under the reused
      // key; if nothing is recoverable this is genuinely a first send.
      const recovered = await recoverRenamedPayload(notifications, key)
      return verifiedDelivery(await notifications.createNotifications(
        recovered ? { ...payload, data: recovered } : payload,
      ))
    }
    if (prior.status === "success") return prior
    const retryable = prior.status === "failure" || (prior.status === "pending" && priorAgeMs(prior) > STALE_PENDING_MS)
    if (retryable) {
      // The unique idempotency key moves aside; the failed attempt stays queryable.
      await notifications.updateNotifications([{ id: prior.id, idempotency_key: `${key}:attempt:${prior.id}` }])
      const data = isPayloadData(prior.data) ? prior.data : payload.data
      return verifiedDelivery(await notifications.createNotifications({ ...payload, data }))
    }
    throw new NotificationRetryError(`Notification ${payload.template} to ${prior.id} is still pending; retry later`)
  }, { timeout: 30 })
}

/**
 * The rename that frees an idempotency key and the create that reuses it are
 * two persistence phases; a crash between them leaves the original key
 * absent while the renamed `<key>:attempt:<id>` records still exist. The
 * oldest attempt's data is the payload the provider's idempotency memory was
 * primed with, so that is the content a later retry must reuse.
 */
async function recoverRenamedPayload(notifications: NotificationRecords, key: string): Promise<Record<string, unknown> | null> {
  try {
    const attempts = await notifications.listNotifications({ idempotency_key: { $like: `${key}:attempt:%` } })
    const renamed = (attempts ?? [])
      .filter((attempt): attempt is NotificationRecordShape & { idempotency_key: string } =>
        typeof attempt.idempotency_key === "string" && attempt.idempotency_key.startsWith(`${key}:attempt:`))
      .sort((a, b) => new Date(a.created_at).getTime() - new Date(b.created_at).getTime())
    const original = renamed[0]
    return original && isPayloadData(original.data) ? original.data : null
  } catch {
    // Recovery is best-effort: without it the send still goes out, it just
    // re-enters the pre-fix behaviour for this edge instead of failing.
    return null
  }
}

/**
 * Manual re-send entry for operations: re-creates the delivery from the
 * stored notification record under a fresh idempotency key, keeping the
 * original linked for auditing. Templates that embed short-lived credentials
 * cannot copy the stored data blindly:
 * - password_reset: the reset token belongs to the auth module and may already
 *   be consumed or expired — re-sending it hands the customer a dead link. The
 *   customer must request a fresh link instead.
 * - order_placed / order_access: mint a fresh emailed-claim link through
 *   orderAccessUrl, the same authorized signing path the original send used.
 * - everything else carries no credential and is re-sent as stored.
 */
export async function resendNotification(container: MedusaContainer, notificationId: string) {
  const notifications = container.resolve(Modules.NOTIFICATION) as unknown as NotificationRecords
  let record: NotificationRecordShape
  try {
    record = await notifications.retrieveNotification(notificationId)
  } catch {
    return { sent: false, reason: "not_found" as const }
  }
  if (!record?.to || !record.channel || !record.template) return { sent: false, reason: "incomplete" as const }
  if (record.template === "password_reset") {
    return { sent: false, reason: "stale_link" as const, message: "Password reset links cannot be re-sent; ask the customer to request a new link." }
  }
  const data: Record<string, unknown> = isPayloadData(record.data) ? { ...record.data } : {}
  if (record.template === "order_placed" || record.template === "order_access") {
    const orderId = typeof data.id === "string" && /^order_[a-zA-Z0-9_-]{1,128}$/.test(data.id)
      ? data.id
      : typeof data.order_id === "string" && /^order_[a-zA-Z0-9_-]{1,128}$/.test(data.order_id)
        ? data.order_id
        : null
    if (!orderId) return { sent: false, reason: "incomplete" as const }
    data.access_url = orderAccessUrl(orderId)
  }
  const created = await notifications.createNotifications({
    to: record.to,
    channel: record.channel,
    template: record.template,
    idempotency_key: `${record.idempotency_key || record.id}:resend:${Date.now()}`,
    data,
  })
  return { sent: true, notification: created }
}
